// Generates src/types/database.ts from supabase/migrations, using PGlite, in the
// same shape as `supabase gen types typescript`. Once a Supabase project is
// connected, `npm run db:types:remote` produces the official file instead.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const db = await PGlite.create();
await db.exec(readFileSync(path.join(root, "supabase/tests/supabase-shim.sql"), "utf8"));
const migrations = path.join(root, "supabase/migrations");
for (const file of readdirSync(migrations).filter((f) => f.endsWith(".sql")).sort()) {
  await db.exec(readFileSync(path.join(migrations, file), "utf8"));
}

const q = async (sql) => (await db.query(sql)).rows;

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid
   where t.typnamespace = 'public'::regnamespace
   group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt) {
  const isArray = udt.startsWith("_");
  const base = isArray ? udt.slice(1) : udt;
  let ts;
  if (enumNames.has(base)) ts = `Database["public"]["Enums"]["${base}"]`;
  else if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(base)) ts = "number";
  else if (base === "bool") ts = "boolean";
  else if (["json", "jsonb"].includes(base)) ts = "Json";
  else if (base === "void") ts = "undefined";
  else ts = "string";
  return isArray ? `${ts}[]` : ts;
}

const columns = await q(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
         (c.column_default is not null or c.is_identity = 'YES') as has_default,
         c.is_identity = 'YES' and c.identity_generation = 'ALWAYS' as always_generated
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
   where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
   order by c.table_name, c.ordinal_position`);

const tables = new Map();
for (const col of columns) {
  if (!tables.has(col.table_name)) tables.set(col.table_name, []);
  tables.get(col.table_name).push(col);
}

const functions = await q(`
  select p.proname as name, p.proretset as retset, rt.typname as ret, rt.typtype as ret_kind,
         coalesce(p.proargnames, '{}') as arg_names,
         coalesce(p.proargmodes::text[], '{}') as arg_modes,
         array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(oid, n)
                join pg_type t on t.oid = u.oid order by n) as arg_types,
         p.pronargdefaults as n_defaults, p.pronargs as n_in
    from pg_proc p join pg_type rt on rt.oid = p.prorettype
   where p.pronamespace = 'public'::regnamespace and rt.typname <> 'trigger'
   order by p.proname`);

const lines = [];
lines.push("// Generated by scripts/gen-types.mjs from supabase/migrations. Do not edit by hand.");
lines.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];", "");
lines.push("export type Database = {", "  public: {", "    Tables: {");
for (const [table, cols] of tables) {
  lines.push(`      ${table}: {`);
  lines.push("        Row: {");
  for (const c of cols) lines.push(`          ${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
  lines.push("        };", "        Insert: {");
  for (const c of cols) {
    if (c.always_generated) continue;
    const optional = c.nullable || c.has_default ? "?" : "";
    lines.push(`          ${c.column_name}${optional}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
  }
  lines.push("        };", "        Update: {");
  for (const c of cols) {
    if (c.always_generated) continue;
    lines.push(`          ${c.column_name}?: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
  }
  lines.push("        };", "        Relationships: [];", "      };");
}
lines.push("    };", "    Views: { [_ in never]: never };", "    Functions: {");
for (const fn of functions) {
  const inArgs = [];
  const outCols = [];
  fn.arg_types.forEach((type, i) => {
    const mode = fn.arg_modes[i] ?? "i";
    const name = fn.arg_names[i];
    if (mode === "i" || mode === "b") inArgs.push({ name, type });
    if (mode === "t" || mode === "o" || mode === "b") outCols.push({ name, type });
  });
  const firstDefault = fn.n_in - fn.n_defaults;
  const args = inArgs.length
    ? `{ ${inArgs.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${tsType(a.type)}`).join("; ")} }`
    : "never";
  let returns;
  if (outCols.length) returns = `{ ${outCols.map((c) => `${c.name}: ${tsType(c.type)}`).join("; ")} }`;
  else if (fn.ret_kind === "c") returns = `Database["public"]["Tables"]["${fn.ret}"]["Row"]`;
  else returns = tsType(fn.ret);
  if (fn.retset) returns = `${returns}[]`;
  lines.push(`      ${fn.name}: { Args: ${args}; Returns: ${returns} };`);
}
lines.push("    };", "    Enums: {");
for (const e of enums) lines.push(`      ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")};`);
lines.push("    };", "    CompositeTypes: { [_ in never]: never };", "  };", "};", "");
lines.push('export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];');
lines.push('export type Enums<T extends keyof Database["public"]["Enums"]> = Database["public"]["Enums"][T];', "");

const out = path.join(root, "src/types/database.ts");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
await db.close();
console.log(`Wrote ${path.relative(root, out)}: ${tables.size} tables, ${functions.length} functions, ${enums.length} enums`);
